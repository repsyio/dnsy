//! Zone model and its JSON file format.

use std::collections::BTreeMap;

use dnsy_proto::{Name, RData, RecordType, Soa};
use serde::{Deserialize, Serialize};

use crate::policy::DnssecPolicy;

/// Errors loading, validating or storing a zone.
#[derive(Debug, thiserror::Error)]
pub enum ZoneError {
    #[error("invalid JSON: {0}")]
    Json(#[from] serde_json::Error),
    #[error("{0}")]
    Invalid(String),
    #[error("i/o error: {0}")]
    Io(#[from] std::io::Error),
}

fn invalid<T>(msg: impl Into<String>) -> Result<T, ZoneError> {
    Err(ZoneError::Invalid(msg.into()))
}

/// One resource record of a zone.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Record {
    pub name: Name,
    pub ttl: u32,
    pub rdata: RData,
}

/// A validated zone.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Zone {
    pub origin: Name,
    pub default_ttl: u32,
    pub soa_ttl: u32,
    pub soa: Soa,
    /// Records other than the SOA, in file order.
    pub records: Vec<Record>,
    pub dnssec: Option<DnssecPolicy>,
}

#[derive(Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct ZoneFile {
    schema: u32,
    origin: String,
    default_ttl: u32,
    soa: SoaFile,
    #[serde(default)]
    records: Vec<RecordFile>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    dnssec: Option<DnssecPolicy>,
}

#[derive(Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct SoaFile {
    mname: String,
    rname: String,
    serial: u32,
    refresh: u32,
    retry: u32,
    expire: u32,
    minimum: u32,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    ttl: Option<u32>,
}

#[derive(Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct RecordFile {
    name: String,
    #[serde(rename = "type")]
    rtype: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    ttl: Option<u32>,
    value: String,
}

const SCHEMA: u32 = 1;

/// Record types a zone file may hold. SOA has its own block; DNSSEC types are owned by signing.
fn parse_type(s: &str) -> Result<RecordType, ZoneError> {
    Ok(match s.to_ascii_uppercase().as_str() {
        "A" => RecordType::A,
        "AAAA" => RecordType::Aaaa,
        "NS" => RecordType::Ns,
        "CNAME" => RecordType::Cname,
        "PTR" => RecordType::Ptr,
        "MX" => RecordType::Mx,
        "TXT" => RecordType::Txt,
        "SRV" => RecordType::Srv,
        "CAA" => RecordType::Caa,
        "DS" => RecordType::Ds,
        "SOA" => return invalid("SOA belongs in the \"soa\" block, not in records"),
        "DNSKEY" | "RRSIG" | "NSEC" | "NSEC3" | "NSEC3PARAM" | "CDS" | "CDNSKEY" => {
            return invalid(format!(
                "{s} records are generated by signing and cannot be written by hand"
            ));
        }
        _ => return invalid(format!("unsupported record type {s}")),
    })
}

fn parse_name(s: &str, what: &str) -> Result<Name, ZoneError> {
    Name::from_ascii(s).or_else(|e| invalid(format!("{what} {s:?}: {e}")))
}

/// Resolves a record owner: `@` is the origin, a trailing dot is absolute, anything else is
/// relative to the origin.
fn owner(s: &str, origin: &Name) -> Result<Name, ZoneError> {
    let name = if s == "@" {
        origin.clone()
    } else if s.ends_with('.') && !s.ends_with("\\.") {
        parse_name(s, "record name")?
    } else {
        parse_name(&format!("{s}.{origin}"), "record name")?
    };
    if !name.is_subdomain_of(origin) {
        return invalid(format!("record name {s:?} is outside the zone {origin}"));
    }
    Ok(name)
}

/// The file name (without directory) for a zone origin: lowercase, no trailing dot, only
/// `[a-z0-9.-]`; the root zone is `_root.json`. Names that cannot be expressed are rejected.
///
/// # Errors
/// Fails on invalid zone data or an i/o error.
pub fn zone_file_name(origin: &Name) -> Result<String, ZoneError> {
    if origin.is_root() {
        return Ok("_root.json".into());
    }
    let text = origin.to_string().to_ascii_lowercase();
    let stem = text.strip_suffix('.').unwrap_or(&text);
    let safe = stem
        .bytes()
        .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'.' || b == b'-');
    if !safe || stem.starts_with('.') || stem.contains("..") {
        return invalid(format!("zone name {origin} is not usable as a file name"));
    }
    Ok(format!("{stem}.json"))
}

impl Zone {
    /// Parses and validates a zone file. Warnings (accepted but discouraged settings) are
    /// returned alongside the zone.
    ///
    /// # Errors
    /// Fails on invalid zone data or an i/o error.
    pub fn from_json(text: &str) -> Result<(Zone, Vec<String>), ZoneError> {
        let file: ZoneFile = serde_json::from_str(text)?;
        if file.schema != SCHEMA {
            return invalid(format!("unsupported schema {}", file.schema));
        }
        let origin = parse_name(&file.origin, "origin")?;
        zone_file_name(&origin)?;
        let soa = Soa {
            mname: parse_name(&file.soa.mname, "soa.mname")?,
            rname: parse_name(&file.soa.rname, "soa.rname")?,
            serial: file.soa.serial,
            refresh: file.soa.refresh,
            retry: file.soa.retry,
            expire: file.soa.expire,
            minimum: file.soa.minimum,
        };
        let mut records = Vec::with_capacity(file.records.len());
        for r in &file.records {
            let rtype = parse_type(&r.rtype)?;
            let name = owner(&r.name, &origin)?;
            let rdata = RData::parse(rtype, &r.value)
                .or_else(|e| invalid(format!("{} {} {:?}: {e}", r.name, r.rtype, r.value)))?;
            records.push(Record {
                name,
                ttl: r.ttl.unwrap_or(file.default_ttl),
                rdata,
            });
        }
        check_cname_exclusivity(&records, &origin)?;
        check_ds_at_delegations(&records, &origin)?;
        let mut warnings = Vec::new();
        if let Some(policy) = &file.dnssec {
            warnings = policy.validate()?;
        }
        let zone = Zone {
            origin,
            default_ttl: file.default_ttl,
            soa_ttl: file.soa.ttl.unwrap_or(file.default_ttl),
            soa,
            records,
            dnssec: file.dnssec,
        };
        Ok((zone, warnings))
    }

    /// Serialises to the JSON file format (absolute names, pretty-printed).
    ///
    /// # Panics
    /// Never in practice: the file structs always serialise.
    #[must_use]
    pub fn to_json(&self) -> String {
        let file = ZoneFile {
            schema: SCHEMA,
            origin: self.origin.to_string(),
            default_ttl: self.default_ttl,
            soa: SoaFile {
                mname: self.soa.mname.to_string(),
                rname: self.soa.rname.to_string(),
                serial: self.soa.serial,
                refresh: self.soa.refresh,
                retry: self.soa.retry,
                expire: self.soa.expire,
                minimum: self.soa.minimum,
                ttl: Some(self.soa_ttl),
            },
            records: self
                .records
                .iter()
                .map(|r| RecordFile {
                    name: r.name.to_string(),
                    rtype: format!("{:?}", r.rdata.rtype()).to_ascii_uppercase(),
                    ttl: Some(r.ttl),
                    value: r.rdata.to_string(),
                })
                .collect(),
            dnssec: self.dnssec.clone(),
        };
        serde_json::to_string_pretty(&file).expect("zone file serialises")
    }

    /// The zone as input to [`dnsy_dnssec::ZoneSigner`]: the SOA (with its own TTL) followed by
    /// every record, class IN.
    #[must_use]
    pub fn signing_data(&self) -> dnsy_dnssec::ZoneData {
        let record = |name: &Name, ttl: u32, data: &RData| dnsy_proto::Record {
            name: name.clone(),
            rtype: data.rtype(),
            class: dnsy_proto::Class::In,
            ttl,
            data: data.clone(),
        };
        let soa = RData::Soa(self.soa.clone());
        let records = std::iter::once(record(&self.origin, self.soa_ttl, &soa))
            .chain(
                self.records
                    .iter()
                    .map(|r| record(&r.name, r.ttl, &r.rdata)),
            )
            .collect();
        dnsy_dnssec::ZoneData {
            origin: self.origin.clone(),
            records,
        }
    }

    /// The file name this zone is stored under.
    ///
    /// # Errors
    /// Fails on invalid zone data or an i/o error.
    pub fn file_name(&self) -> Result<String, ZoneError> {
        zone_file_name(&self.origin)
    }
}

/// DS belongs to the parent side of a zone cut (RFC 4035 2.4): only at a delegation point.
fn check_ds_at_delegations(records: &[Record], origin: &Name) -> Result<(), ZoneError> {
    for r in records.iter().filter(|r| r.rdata.rtype() == RecordType::Ds) {
        let delegated = r.name != *origin
            && records
                .iter()
                .any(|n| n.name == r.name && n.rdata.rtype() == RecordType::Ns);
        if !delegated {
            return invalid(format!(
                "DS at {} needs an NS record there: DS is only allowed at a delegation point",
                r.name
            ));
        }
    }
    Ok(())
}

fn check_cname_exclusivity(records: &[Record], origin: &Name) -> Result<(), ZoneError> {
    let mut by_name: BTreeMap<&Name, (usize, usize)> = BTreeMap::new();
    for r in records {
        let e = by_name.entry(&r.name).or_default();
        if r.rdata.rtype() == RecordType::Cname {
            e.0 += 1;
        } else {
            e.1 += 1;
        }
    }
    for (name, (cnames, others)) in by_name {
        if cnames > 1 || (cnames == 1 && (others > 0 || name == origin)) {
            return invalid(format!(
                "CNAME at {name} cannot coexist with other records (RFC 1034 3.6.2)"
            ));
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    const EXAMPLE: &str = include_str!("../tests/fixtures/example.com.json");

    fn with_records(records: &str) -> String {
        format!(
            r#"{{"schema":1,"origin":"example.com.","default_ttl":60,
            "soa":{{"mname":"ns.example.com.","rname":"h.example.com.","serial":1,"refresh":1,"retry":1,"expire":1,"minimum":1}},
            "records":[{records}]}}"#
        )
    }

    fn err(json: &str) -> String {
        Zone::from_json(json).unwrap_err().to_string()
    }

    #[test]
    fn example_zone_loads() {
        let (zone, warnings) = Zone::from_json(EXAMPLE).unwrap();
        assert_eq!(warnings.len(), 0);
        assert_eq!(zone.origin.to_string(), "example.com.");
        assert_eq!(zone.records.len(), 10);
        assert_eq!(zone.records[0].ttl, 3600);
        assert_eq!(zone.records[3].ttl, 300);
        assert_eq!(zone.records[6].name.to_string(), "mail.example.com.");
        assert!(!zone.dnssec.as_ref().unwrap().enabled);
        let (again, _) = Zone::from_json(&zone.to_json()).unwrap();
        assert_eq!(again, zone);
    }

    #[test]
    fn zone_file_name_normalisation() {
        let n = |s| zone_file_name(&Name::from_ascii(s).unwrap()).unwrap();
        assert_eq!(n("Example.COM."), "example.com.json");
        assert_eq!(n("example.com"), "example.com.json");
        assert_eq!(n("."), "_root.json");
        assert_eq!(n("xn--bcher-kva.example."), "xn--bcher-kva.example.json");
        for bad in [
            "a/b.example.",
            "a\\\\b.example.",
            "under_score.example.",
            "a\\046b.example.",
        ] {
            let name = Name::from_ascii(bad).unwrap();
            assert!(zone_file_name(&name).is_err(), "{bad}");
        }
        assert!(Name::from_ascii("bücher.example.").is_err());
        assert!(Name::from_ascii("../x.").is_err());
        assert!(Name::from_ascii("a..b.").is_err());
    }

    #[test]
    fn cname_exclusivity_rejected() {
        let cname = r#"{"name":"w","type":"CNAME","value":"x.example.com."}"#;
        let a = r#"{"name":"w","type":"A","value":"192.0.2.1"}"#;
        assert!(err(&with_records(&format!("{cname},{a}"))).contains("CNAME"));
        assert!(err(&with_records(&format!("{cname},{cname}"))).contains("CNAME"));
        let apex = r#"{"name":"@","type":"CNAME","value":"x.example.com."}"#;
        assert!(err(&with_records(apex)).contains("CNAME"));
        assert!(Zone::from_json(&with_records(cname)).is_ok());
    }

    #[test]
    fn ds_only_at_delegations() {
        let ds = r#"{"name":"sub","type":"DS","value":"1 13 2 AABB"}"#;
        let ns = r#"{"name":"sub","type":"NS","value":"ns.example.net."}"#;
        assert!(err(&with_records(ds)).contains("delegation"));
        let apex = r#"{"name":"@","type":"DS","value":"1 13 2 AABB"}"#;
        assert!(err(&with_records(&format!("{apex},{ns}"))).contains("delegation"));
        assert!(Zone::from_json(&with_records(&format!("{ds},{ns}"))).is_ok());
    }

    #[test]
    fn manual_rrsig_rejected() {
        for t in [
            "RRSIG",
            "DNSKEY",
            "NSEC",
            "NSEC3",
            "NSEC3PARAM",
            "cds",
            "CDNSKEY",
        ] {
            let rec = format!(r#"{{"name":"@","type":"{t}","value":"x"}}"#);
            assert!(err(&with_records(&rec)).contains("signing"), "{t}");
        }
    }

    #[test]
    fn validation_errors() {
        assert!(
            err(&with_records(
                r#"{"name":"x.other.org.","type":"A","value":"192.0.2.1"}"#
            ))
            .contains("outside")
        );
        assert!(err(&with_records(r#"{"name":"@","type":"SOA","value":"x"}"#)).contains("soa"));
        assert!(
            err(&with_records(r#"{"name":"@","type":"HINFO","value":"x"}"#))
                .contains("unsupported")
        );
        assert!(
            err(&with_records(r#"{"name":"@","type":"A","value":"nope"}"#)).contains("invalid")
        );
        assert!(err(&with_records("").replace("schema", "x")).contains("JSON"));
        assert!(err(&with_records("").replace("\"schema\":1", "\"schema\":2")).contains("schema"));
        assert!(err("{}").contains("JSON"));
        assert!(
            err(&with_records("").replace("example.com.\",\"default", "bad_name.\",\"default"))
                .contains("file name")
        );
    }

    #[test]
    fn dnssec_warning_surfaces() {
        let json = with_records("").replace(
            "\"records\":[]",
            r#""dnssec":{"enabled":true,"nsec3":{"iterations":2,"allow_nonzero_iterations":true}}"#,
        );
        let (_, warnings) = Zone::from_json(&json).unwrap();
        assert_eq!(warnings.len(), 1);
    }
}
